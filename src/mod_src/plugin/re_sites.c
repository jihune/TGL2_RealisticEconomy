int re_sites_verify(BYTE *base, int group, void (*report)(const char *line))
{
    int bad = 0;
    for (size_t i = 0; i < sizeof SITES / sizeof SITES[0]; i++) {
        const site *s = &SITES[i];
        if (s->group != group)
            continue;
        BYTE *at = base + (s->va - RE_IMAGE_BASE);
        BYTE expect[12];
        int count = s->count;
        if (count == 0) {
            LONG delta = (LONG)(s->target - (s->va + 5));
            expect[0] = 0xE8;
            memcpy(expect + 1, &delta, 4);
            count = 5;
        } else {
            memcpy(expect, s->bytes, (size_t)count);
            if (s->target) {
                const BYTE *constant = base + (s->target - RE_IMAGE_BASE);
                memcpy(expect + count, &constant, 4);
                count += 4;
            }
        }
        int ok = re_bytes_equal(at, expect, (SIZE_T)count);
        bad += !ok;
        if (report) {
            char line[160];
            snprintf(line, sizeof line, "  site %-20s va=0x%08x %s", s->name, s->va, ok ? "ok" : "MISMATCH");
            report(line);
        }
    }
    return bad;
}
